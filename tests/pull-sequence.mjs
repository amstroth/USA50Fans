import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../frontend/src/pull-sequence.js',import.meta.url),'utf8');
const {RARITY_ORDER,arrangePullRewards,buildPullRevealSteps,isShowcaseReward}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));

const card=(rarity,id)=>({type:'card',card:{id,rarity,title:id}});
const points=(id)=>({type:'pullPoints',amount:id});
const ticket=(id)=>({type:'idolTicket',idolId:id});
const coupon={type:'merchCoupon',discountPercent:10};
const draws=[card('R','r1'),points(40),card('MR','m1'),card('SR','sr1'),ticket('jaylene'),
 card('UR','u1'),card('SSR','ssr1'),coupon,card('R','r2'),card('MR','m2')];
const original=draws.slice(),arranged=arrangePullRewards(draws);
const order=arranged.map(x=>x.reward.card?.id||x.reward.type+(x.reward.amount||x.reward.idolId||''));
assert.deepEqual(order,['u1','m1','m2','ssr1','pullPoints40','idolTicketjaylene','merchCoupon','sr1','r1','r2']);
assert.deepEqual(draws,original,'Presentation cannot mutate the server-generated draw order');
assert.deepEqual(arranged.map(x=>x.drawIndex),[5,2,9,6,1,4,7,3,0,8],'Stable original draw indexes retained');
assert.equal(RARITY_ORDER.UR>RARITY_ORDER.MR,true);
assert.equal(RARITY_ORDER.MR>RARITY_ORDER.SSR,true);
assert.equal(RARITY_ORDER.SSR>RARITY_ORDER.SR,true);
assert.equal(RARITY_ORDER.SR>RARITY_ORDER.R,true);
assert.equal(isShowcaseReward(card('UR','x')),true);
assert.equal(isShowcaseReward(card('MR','x')),true);
assert.equal(isShowcaseReward(card('SSR','x')),true);
assert.equal(isShowcaseReward(card('SR','x')),false);
assert.equal(isShowcaseReward(card('R','x')),false);
assert.equal(isShowcaseReward(ticket('z')),false);
const steps=buildPullRevealSteps(arranged);
assert.deepEqual(steps.map(s=>s.type),['showcase','showcase','showcase','showcase','collectible','collectible','collectible','common']);
assert.equal(steps[0].items[0].reward.card.id,'u1','UR reveals first');
assert.equal(steps[3].items[0].reward.card.id,'ssr1','SSR reveals individually');
assert.equal(steps.at(-1).items.length,3,'All SR and R cards appear together');
assert.deepEqual(steps.at(-1).items.map(x=>x.reward.card.rarity),['SR','R','R']);
assert.equal(steps.reduce((n,s)=>n+s.items.length,0),draws.length,'All rewards reveal once');
assert.equal(steps[0].duration>steps[4].duration,true,'High-rarity spin receives the longer animation');
assert.equal(buildPullRevealSteps(arrangePullRewards([card('R','only')])).length,1,'Single R skips extended spin');
assert.equal(buildPullRevealSteps(arrangePullRewards([card('SSR','only')]))[0].type,'showcase');
assert.deepEqual(buildPullRevealSteps(arrangePullRewards([points(125),ticket('miu')] )).map(x=>x.type),['collectible','collectible']);
assert.deepEqual(arrangePullRewards([]),[]);
console.log('Card pull sequence tests passed: UR > MR > SSR, stable randomized extras, SR/R instant group, sequential rare flips, unchanged reward counts.');
